#!/usr/bin/env python3
"""Claude Code hooks for the syseng spec toolkit. `spec init` copies this file to .syseng/hook.

    hook pre-tool     refuses agents' direct edits to the files the toolkit manages (AGENT-20, DR-3)
    hook read-guard   keeps the reasoning-check subagent out of the spec directory (REASON-5, DR-42)
    hook stop         runs the checker when the agent tries to finish (AGENT-12, DR-4)
    hook prompt       records the engineer's explicit chat approvals (AGENT-21, AGENT-33, DR-41)

It uses only the standard library, so the guards are fast and keep working on a machine where
the toolkit isn't set up (DR-40). Claude Code sends each event as JSON on standard input. Exit
code 2 refuses a tool call, and what this prints on standard error tells the agent why.
"""

from __future__ import annotations

import json
import os
import re
import shlex
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
LAUNCHER = HERE / "spec"  # the repository's launcher, which `spec init` writes next to this file
SPEC = ".syseng/spec"     # how agents run the toolkit from the repository root
NOT_SET_UP = 127          # the launcher's exit code when this machine has no toolkit

# ---------------------------------------------------------------- finding spec directories


def spec_root_of(path: Path) -> Path | None:
    """The spec directory a path lies in: the nearest ancestor holding toolkit.yaml and elements/."""
    for d in [path, *path.parents]:
        if (d / "toolkit.yaml").is_file() and (d / "elements").is_dir():
            return d
    return None


def _abs(raw, base: Path) -> Path | None:
    if not raw or not isinstance(raw, str):
        return None
    p = Path(os.path.expanduser(raw))
    return Path(os.path.normpath(str(p if p.is_absolute() else base / p)))


def _spec_roots_near(base: Path) -> list[Path]:
    """Spec directories a search from `base` could reach: spec/ beside this repository and its ancestors."""
    found = []
    for d in [HERE.parent, base, *base.parents]:
        root = d / "spec"
        if root not in found and spec_root_of(root) == root:
            found.append(root)
    return found


# ---------------------------------------------------------------- pre-tool: the spec guard

def _tool_call(event: dict) -> tuple[str, dict, Path]:
    ti = event.get("tool_input")
    return str(event.get("tool_name") or ""), ti if isinstance(ti, dict) else {}, Path(event.get("cwd") or os.getcwd())


def managed(path: Path) -> str | None:
    """How to change a file the toolkit manages, or None when agents may edit it directly."""
    root = spec_root_of(path)
    if root is None or path == root:
        return None
    head = path.relative_to(root).parts[0]
    if head == "elements":
        return (f"Change the spec with `{SPEC} edit`, a YAML batch on standard input (`{SPEC} edit --help` "
                f"shows the format). It shows each edit's context, asks for acknowledgments where they're "
                f"needed, validates the result and logs your reason in the open change.")
    if head == "changes":
        return (f"Change records are written by `{SPEC} change`, `{SPEC} decide`, `{SPEC} resolve` and "
                f"`{SPEC} friction`, and `{SPEC} edit` logs every spec edit in them.")
    if head == "approvals.yaml":
        return (f"Only the engineer approves. When they have explicitly approved named items, record it with "
                f"`{SPEC} approve <IDs> --words \"<their words>\"`.")
    if head == "retired.yaml":
        return f"Removing an item with `{SPEC} edit` retires its ID."
    if head in ("requirements.md", "decisions.md"):
        return f"This view is generated by `{SPEC} render`. Change the spec with `{SPEC} edit` instead."
    if head == "questions.yaml":
        return f"Questions for the engineer go in the open change, with `{SPEC} decide`."
    return None


_SEGMENTS = re.compile(r"\|\||&&|;|\n|(?<![>&<])\|(?!\|)|(?<![>&<0-9])&(?![>&])")
_REDIRECT = re.compile(r"(?:^|[^0-9&<>])>{1,2}\|?\s*(\"[^\"]*\"|'[^']*'|[^\s;&|<>()]+)")
_WRITE_ALL = {"rm", "mv", "truncate", "unlink", "shred", "tee", "remove-item", "move-item", "set-content",
              "add-content", "clear-content", "out-file"}
_WRITE_LAST = {"cp", "install", "ln", "rsync", "copy-item"}
_PREFIXES = {"sudo", "command", "env", "exec", "nice", "time"}


def shell_targets(command: str, cwd: Path) -> list[Path]:
    """Files a shell command plainly writes: redirections, tee, rm/mv/cp and in-place sed or perl.

    A script that opens files itself (python, awk) isn't caught. The change log and the
    auditors are the backstop for those."""
    out: list[Path] = []
    base = cwd
    for seg in _SEGMENTS.split(command):
        for m in _REDIRECT.finditer(seg):
            out.append(_abs(m.group(1).strip("'\""), base))
        try:
            words = shlex.split(seg)
        except ValueError:
            words = seg.split()
        while words and (words[0] in _PREFIXES or re.match(r"^\w+=", words[0])):
            words = words[1:]
        if not words:
            continue
        cmd = os.path.basename(words[0]).lower()
        args = [w for w in words[1:] if not w.startswith("-")]
        if cmd == "cd" and args:
            base = _abs(args[0], base) or base
        elif cmd in _WRITE_ALL:
            out += [_abs(a, base) for a in args]
        elif cmd in _WRITE_LAST and args:
            out.append(_abs(args[-1], base))
        elif (cmd in ("sed", "gsed") and any(w.startswith(("-i", "--in-place")) for w in words[1:])) or \
                (cmd == "perl" and any(re.match(r"^-[pnlaws0-9]*i", w) for w in words[1:])):
            out += [_abs(a, base) for a in args]
    return [p for p in out if p is not None]


def pre_tool(event: dict) -> int:
    tool, ti, cwd = _tool_call(event)
    if tool in ("Bash", "PowerShell"):
        paths = shell_targets(ti.get("command") or "", cwd)
    else:
        paths = [_abs(ti.get("file_path") or ti.get("notebook_path"), cwd)]
    for p in paths:
        hint = managed(p) if p is not None else None
        if hint:
            print(f"{p} is managed by the spec toolkit, so agents don't edit it directly (AGENT-20). {hint}",
                  file=sys.stderr)
            return 2
    return 0


# ---------------------------------------------------------------- read-guard: reasoning checks

def _glob_regex(pattern: str) -> re.Pattern:
    """A path glob as the Glob and Grep tools read it: `**` crosses directories, `*` doesn't."""
    out, i = "", 0
    while i < len(pattern):
        c = pattern[i]
        if pattern.startswith("**/", i):
            out, i = out + "(?:.*/)?", i + 3
            continue
        if pattern.startswith("**", i):
            out, i = out + ".*", i + 2
            continue
        if c == "*":
            out += "[^/]*"
        elif c == "?":
            out += "[^/]"
        elif c == "{":
            j = pattern.find("}", i)
            if j > i:
                out += "(?:" + "|".join(re.escape(alt) for alt in pattern[i + 1:j].split(",")) + ")"
                i = j + 1
                continue
            out += re.escape(c)
        else:
            out += re.escape(c)
        i += 1
    return re.compile(out + r"\Z")


def _reaches(where: Path, roots: list[Path], pattern: str | None, basename_only: bool) -> bool:
    """Whether a search from `where`, filtered by `pattern`, could return a file inside the roots."""
    if not pattern:
        return True
    rx = _glob_regex(pattern)
    for root in roots:
        for dirpath, _, files in os.walk(root):
            for name in files:
                rel = (Path(dirpath) / name).relative_to(where).as_posix()
                target = name if basename_only and "/" not in pattern else rel
                if rx.match(target):
                    return True
    return False


def read_guard(event: dict) -> int:
    tool, ti, cwd = _tool_call(event)
    refusal = None
    if tool in ("Read", "NotebookRead"):
        p = _abs(ti.get("file_path") or ti.get("notebook_path"), cwd)
        if p is not None and spec_root_of(p):
            refusal = f"{p} is inside the spec directory."
    elif tool in ("Grep", "Glob"):
        where = _abs(ti.get("path"), cwd) or cwd
        if spec_root_of(where):
            refusal = f"{where} is inside the spec directory."
        else:
            hidden = [r for r in _spec_roots_near(cwd) if where in r.parents]
            if tool == "Grep":
                filt = ti.get("glob") or (f"*.{ti['type']}" if ti.get("type") else None)
                reaches = _reaches(where, hidden, filt, basename_only=True)
            else:
                pattern = ti.get("pattern") or "**"
                if pattern.startswith("/"):  # an absolute pattern searches from the filesystem root
                    where, hidden = Path("/"), _spec_roots_near(cwd)
                    pattern = pattern.lstrip("/")
                reaches = _reaches(where, hidden, pattern, basename_only=False)
            if hidden and reaches:
                refusal = (f"this search would include the spec directory ({hidden[0]}). Search a directory that "
                           f"doesn't contain it, such as the source directory, or narrow the file pattern.")
    if refusal:
        print(f"Refused: {refusal} A reasoning check reaches its verdict from the product's code alone, so it "
              f"never reads the spec (REASON-5).", file=sys.stderr)
        return 2
    return 0


# ---------------------------------------------------------------- stop: the done gate

def _toolkit(args: list[str], cwd: Path) -> subprocess.CompletedProcess:
    if not LAUNCHER.exists():
        return subprocess.CompletedProcess(args, NOT_SET_UP, "", f"{LAUNCHER} is missing")
    try:
        return subprocess.run([str(LAUNCHER), *args], cwd=str(cwd), capture_output=True, text=True, timeout=100)
    except (OSError, subprocess.TimeoutExpired) as e:
        return subprocess.CompletedProcess(args, NOT_SET_UP, "", str(e))


def _work_dir(event: dict) -> Path:
    """Where the agent works: its cwd when that's inside a repository with a spec, else the project."""
    cwd = Path(event.get("cwd") or os.getcwd())
    for d in [cwd, *cwd.parents]:
        if (d / "spec" / "toolkit.yaml").is_file():
            return d
    return Path(os.environ.get("CLAUDE_PROJECT_DIR") or HERE.parent)


def _setup_notice(what: str) -> str:
    return (f"The spec toolkit isn't set up on this machine, so {what}. Install it and run `spec init` "
            f"in this repository.")


def stop(event: dict) -> int:
    if event.get("stop_hook_active"):  # block at most once per turn, so a question still gets through
        return 0
    run = _toolkit(["check"], _work_dir(event))
    if run.returncode == 0:
        return 0
    if run.returncode == 1 and "error[" in run.stdout:
        print(json.dumps({"decision": "block", "reason":
                          "The spec has errors, so this work isn't finished (AGENT-12). Fix each one, then "
                          "finish. If you're stopping to ask the engineer something, ask now.\n\n"
                          + run.stdout.strip()}))
        return 0
    if run.returncode == NOT_SET_UP:
        print(json.dumps({"systemMessage": _setup_notice("the spec wasn't checked")}))
    else:
        detail = (run.stderr or run.stdout).strip().splitlines()
        print(json.dumps({"systemMessage": "spec check couldn't run: " + (detail[-1] if detail else "no output")}))
    return 0


# ---------------------------------------------------------------- prompt: chat approvals

_PASTED = re.compile(r'<pasted_content id="[^"]*">.*?</pasted_content id="[^"]*">', re.S)
_LOOSE = re.compile(r"\b(lgtm|looks good|sgtm|ship it|approved?)\b", re.I)
_ID = r"[A-Za-z][A-Za-z0-9]*-[Vv]?\d+"
_TOKEN = re.compile(rf"\s*(?:(?P<filler>\bplease\b|\bthanks\b|\bthank you\b|\blgtm\b|\bsgtm\b)|"
                    rf"(?P<id>{_ID}(?:\.\.(?:{_ID}|\d+))?)|(?P<word>(?-i:\b[A-Z][A-Z0-9]*\b))|"
                    rf"(?P<sep>,|&|\+|\band\b))\s*", re.I)
_CLAUSE_END = re.compile(r"[.!?;:](?=\s|$)|\n| [-\u2013\u2014] ")
_LEAD = re.compile(r"^\s*approved?\b:?", re.I)
_ENDORSE = re.compile(r"^(?P<clause>.*?)[\s,:\-\u2013\u2014]*\b(?:lgtm|sgtm|approved|looks? good)\b[\s.!]*$", re.I)


def _ids_only(clause: str, elements: set[str] | None) -> tuple[list[str], str | None]:
    """The IDs a clause names, if it names nothing else. Bare capitalized words count as
    system element IDs only when they are elements (any, when `elements` is None)."""
    ids, pos = [], 0
    while pos < len(clause):
        m = _TOKEN.match(clause, pos)
        word = m.group("word") if m else None
        if not m or m.end() == pos or (word and elements is not None and word not in elements):
            return [], f"\"{clause.strip()}\" doesn't name its items by ID only"
        if m.group("id") or word:
            ids.append((m.group("id") or word).upper())
        pos = m.end()
    if not ids:
        return [], "it doesn't name any items"
    return ids, None


def parse_approval(line: str, elements: set[str] | None = None) -> tuple[list[str] | None, str | None]:
    """The items one line of the engineer's message approves (DR-41).

    A line approves when it starts with "approve" and its first clause names only IDs and ranges
    ("approve CHECK-3, CHECK-5..7."), or when it is only IDs followed by LGTM, "approved" or "looks
    good" ("SYS-32 LGTM"). Returns (None, None) for a line that approves nothing, and ([], why)
    for one that needs the engineer to confirm a list, such as "approve everything except …"."""
    if _LEAD.match(line):
        return _ids_only(_CLAUSE_END.split(_LEAD.sub("", line, count=1), maxsplit=1)[0], elements)
    m = _ENDORSE.match(line)
    if m:
        ids, problem = _ids_only(m.group("clause"), elements)
        if ids or re.search(_ID, m.group("clause")):
            return ids, problem
    return None, None


def prompt(event: dict) -> int:
    words = _PASTED.sub("", event.get("prompt") or "").strip()  # pasted text isn't the engineer's words
    where = _work_dir(event)
    edir = where / "spec" / "elements"
    elements = {d.name for d in edir.iterdir() if d.is_dir()} if edir.is_dir() else None
    own = [line.strip() for line in words.splitlines() if not line.lstrip().startswith(">")]  # quotes aren't
    ids, unclear = [], []                                                                        # approvals
    for line in own:
        found, problem = parse_approval(line, elements)
        if problem:
            unclear.append(f"\"{line.strip()}\": {problem}")
        ids += [i for i in found or [] if i not in ids]
    if unclear:
        print("Note from the spec toolkit: the engineer's message reads as an approval the toolkit can't pin to "
              f"exact items, so it recorded nothing for it (DR-41): {'; '.join(unclear)}. Show the engineer the exact "
              "items you'd approve, leaving out every item an exception could refer to (AGENT-43), and ask them to "
              f"confirm. Use a menu if you have one. Then record their answer with `{SPEC} approve`.")
    if not ids:
        if not unclear and _LOOSE.search("\n".join(own)):
            print("Note from the spec toolkit: this message approves no spec items (AGENT-33). An approval in chat "
                  "names the items, as in \"approve CHECK-3\" or \"CHECK-3 LGTM\", so don't record one from it.")
        return 0
    run = _toolkit(["approve", *ids, "--words", words[:2000], "--via", "chat"], where)
    if run.returncode == NOT_SET_UP:
        print("Note from the spec toolkit: " + _setup_notice("this approval wasn't recorded") +
              " Tell the engineer.")
    elif run.returncode != 0:
        detail = (run.stdout + run.stderr).strip().rstrip(".")
        print(f"Note from the spec toolkit: the engineer's approval wasn't recorded ({detail}). Tell the engineer.")
    else:
        print("Note from the spec toolkit: the engineer approved these items in this message, and the approval is "
              f"recorded, so don't record it again.\n{run.stdout.strip()}\nIf you changed any of them after you "
              "last showed them to the engineer, say so now: the approval covers them as they are.")
    return 0


# ---------------------------------------------------------------- entry point

HANDLERS = {"pre-tool": pre_tool, "read-guard": read_guard, "stop": stop, "prompt": prompt}


def main(argv: list[str]) -> int:
    if len(argv) != 2 or argv[1] not in HANDLERS:
        print(f"usage: hook {{{'|'.join(HANDLERS)}}} < event.json", file=sys.stderr)
        return 1
    try:
        event = json.load(sys.stdin)
    except ValueError:
        return 0  # not an event this script understands; never block on it
    return HANDLERS[argv[1]](event if isinstance(event, dict) else {})


if __name__ == "__main__":
    sys.exit(main(sys.argv))
